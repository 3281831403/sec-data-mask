"""Black-box contract tests for the data-masking view engine.

These 15 tests are the fixed specification. Do not edit this file while
fixing ``engine/mask/view.py``. The initial stub-only repository must report
exactly 15 failures, one per test, with no collection or import errors.
"""

from engine.mask.view import (
    aggregate_guard,
    audit_access,
    export_view,
    field_rules,
    mask_batch,
    mask_record,
    mask_value,
    validate_policy,
)

ID_CARD = "110101199001011234"
PHONE = "13800138000"
NAME = "张三"
EMAIL = "zhangsan@example.com"
MASKED = "REDACTED"

SCHEMA = [
    {"name": "id", "kind": "id", "scope": "list"},
    {"name": "name", "kind": "name", "scope": "list"},
    {"name": "phone", "kind": "phone", "scope": "list"},
    {"name": "id_card", "kind": "id_card", "scope": "detail"},
    {"name": "email", "kind": "email", "scope": "detail"},
    {"name": "dept", "kind": "text", "scope": "detail"},
    {"name": "amount", "kind": "amount", "scope": "detail"},
]

POLICY = {
    "schema": SCHEMA,
    "fields": {
        "id": {"kind": "id", "sensitive": False},
        "name": {"kind": "name"},
        "phone": {"kind": "phone"},
        "id_card": {"kind": "id_card"},
        "email": {"kind": "email"},
        "dept": {"kind": "text", "group_by": True},
        "amount": {"kind": "amount", "aggregate": "avg", "as": "avg_amount"},
    },
    "default": {"kind": "text", "sensitive": True},
    "aggregate": {"min_group_size": 5},
    "export": {"formats": ["json", "csv"], "bypass_masking": False},
}

RECORD = {
    "id": "c-1001",
    "name": NAME,
    "phone": PHONE,
    "id_card": ID_CARD,
    "email": EMAIL,
    "dept": "售后",
    "amount": 8800,
}


def _rules():
    return field_rules(SCHEMA, POLICY)


def test_detail_page_only_fields_are_covered_by_the_rule_map():
    # Defect 1 / 详情页泄漏断言: the map must be derived from the whole
    # schema, not just the list-page subset.
    list_only = {
        "id": {"kind": "id", "sensitive": False},
        "name": {"kind": "name"},
        "phone": {"kind": "phone"},
    }
    policy = {**POLICY, "fields": list_only}
    rules = field_rules(SCHEMA, policy)

    assert "id_card" in rules
    assert rules["id_card"]["kind"] == "id_card"
    assert rules["id_card"]["sensitive"] is True

    masked = mask_record(RECORD, rules, "agent")
    assert masked["id_card"] == MASKED


def test_new_schema_field_without_explicit_rule_defaults_to_masked():
    # Defect 2 / 新增字段泄漏断言: a field added to the schema but not yet
    # configured in policy must still be masked.
    schema = SCHEMA + [{"name": "wechat", "kind": "text", "scope": "detail"}]
    record = {**RECORD, "wechat": "wx_2026"}
    rules = field_rules(schema, POLICY)

    assert "wechat" in rules
    assert rules["wechat"]["sensitive"] is True
    assert mask_record(record, rules, "agent")["wechat"] == MASKED


def test_export_path_uses_the_same_masking_as_the_detail_page():
    # Defect 3 / 导出绕过断言: even when policy asks for an export bypass,
    # the export view must still use the detail-page masking.
    policy = {
        **POLICY,
        "export": {"formats": ["json", "csv"], "bypass_masking": True},
    }
    rules = field_rules(SCHEMA, policy)
    detail = mask_record(RECORD, rules, "agent")
    exported = export_view([RECORD], rules, "agent", "json")

    assert exported["format"] == "json"
    assert exported["count"] == 1
    assert exported["rows"] == [detail]
    assert exported["rows"][0]["id_card"] == MASKED
    assert ID_CARD not in str(exported)


def test_role_check_is_exact_and_does_not_match_admin_prefix():
    # Defect 4 / 角色前缀断言: startswith or substring checks treat
    # admin_readonly, administrator and superadmin as administrators.
    assert mask_value("id_card", ID_CARD, "admin") == ID_CARD
    assert mask_value("id_card", ID_CARD, "admin_readonly") == MASKED
    assert mask_value("id_card", ID_CARD, "administrator") == MASKED
    assert mask_value("id_card", ID_CARD, "superadmin") == MASKED
    assert mask_value("id_card", ID_CARD, "Administrator") == MASKED


def test_aggregate_threshold_is_checked_per_group_not_by_total_rows():
    # Defect 5 / 聚合反推断言: 10 rows total pass a threshold of 5, but the
    # one-row finance group must still be suppressed.
    rows = [{"dept": "售后", "amount": 100} for _ in range(9)]
    rows.append({"dept": "财务", "amount": 999})
    result = aggregate_guard(rows, _rules(), "agent")

    assert "财务" not in result
    assert result["售后"]["count"] == 9


def test_aggregate_values_are_masked_again_before_output():
    # Defect 6 / 聚合二次脱敏断言: the average of five equal salaries is
    # itself an individual value and must not be returned raw.
    rows = [{"dept": "售后", "amount": 8800} for _ in range(5)]
    result = aggregate_guard(rows, _rules(), "agent")

    assert result["售后"]["avg_amount"] == MASKED
    assert result["售后"]["count"] == 5
    assert "8800" not in str(result)


def test_audit_event_records_the_viewed_fields():
    # Defect 7 / 审计断言: a counter alone cannot answer which fields a
    # support agent opened.
    event = audit_access(
        {"id": "u-7", "role": "agent"}, "c-1001", ["id_card", "phone"]
    )

    assert event["user"] == "u-7"
    assert event["role"] == "agent"
    assert event["record_id"] == "c-1001"
    assert event["fields"] == ["id_card", "phone"]
    assert event["field_count"] == 2


def test_policy_validation_reports_coverage_threshold_and_export_bypass():
    # Defect 8 / 策略校验断言: validation must check complete field
    # coverage, not just whether a policy parses.
    broken = {
        "schema": SCHEMA,
        "fields": {
            "id": {"kind": "id", "sensitive": False},
            "name": {"kind": "name"},
            "phone": {"kind": "phone"},
        },
        "default": {"kind": "text", "sensitive": True},
        "aggregate": {"min_group_size": 1},
        "export": {"formats": ["json"], "bypass_masking": True},
    }
    issues = validate_policy(broken)

    assert validate_policy(POLICY) == []
    assert any("id_card" in issue for issue in issues)
    assert any("阈值" in issue for issue in issues)
    assert any("导出" in issue for issue in issues)


def test_batch_processing_does_not_reuse_the_previous_batch_role():
    # Defect 9 / 批次串角色断言: the second batch must use its own agent
    # role even though the first batch used admin.
    batches = [
        {"id": "b1", "role": "admin", "rows": [RECORD]},
        {"id": "b2", "role": "agent", "rows": [RECORD]},
    ]
    result = mask_batch(batches, POLICY, "agent")

    assert result["b1"]["rows"][0]["id_card"] == ID_CARD
    assert result["b2"]["rows"][0]["id_card"] == MASKED


def test_masked_value_does_not_preserve_length_or_format():
    # Defect 10 / 长度格式断言: a fixed-length or partially masked value
    # still exposes the checksum position and can be brute-forced.
    masked = mask_record(RECORD, _rules(), "agent")["id_card"]

    assert masked == MASKED
    assert len(masked) != len(ID_CARD)
    assert not any(character.isdigit() for character in masked)


def test_agent_cannot_see_the_full_identity_number():
    masked = mask_record(RECORD, _rules(), "agent")

    assert masked["id_card"] == MASKED
    assert ID_CARD not in str(masked)
    assert PHONE not in str(masked)


def test_admin_exact_role_sees_the_full_identity_number():
    visible = mask_record(RECORD, _rules(), "admin")

    assert visible["id_card"] == ID_CARD
    assert visible["phone"] == PHONE
    assert visible["name"] == NAME


def test_field_missing_from_schema_and_policy_is_still_masked():
    record = {**RECORD, "nickname": "小王"}
    masked = mask_record(record, _rules(), "agent")

    assert masked["nickname"] == MASKED
    assert "小王" not in str(masked)


def test_small_group_produces_no_aggregate_output():
    rows = [{"dept": "财务", "amount": 999}]
    result = aggregate_guard(rows, _rules(), "agent")

    assert "财务" not in result
    assert result == {}


def test_two_batches_match_processing_each_batch_alone():
    first = {"id": "b1", "role": "agent", "rows": [RECORD]}
    second = {"id": "b2", "role": "admin", "rows": [RECORD]}

    combined = mask_batch([first, second], POLICY, "agent")
    alone_first = mask_batch([first], POLICY, "agent")
    alone_second = mask_batch([second], POLICY, "agent")

    assert combined["b1"] == alone_first["b1"]
    assert combined["b2"] == alone_second["b2"]
    assert combined["b1"]["rows"][0]["id_card"] == MASKED
    assert combined["b2"]["rows"][0]["id_card"] == ID_CARD
